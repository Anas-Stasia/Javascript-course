function calculateBMI(mass, height) {
  return mass / (height ** 2);
}

calculateBMI(78, 1.69); // ≈ 27.3

function calculateAge(birthYear, currentYear) {
  return currentYear - birthYear;
}

calculateAge(2002, 2025); // 23

